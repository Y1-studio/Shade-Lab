// Preserve the supplied PNG bytes while making the guide fully offline.
const fs=require('node:fs'),path=require('node:path');
function build(){
 const sprites={};
 for(const [pose,file,width,height]of [['regular','RMQ2_1.png',133,237],['glasses','RMQ2.png',156,238]]){
  const png=fs.readFileSync(path.join(__dirname,'assets',file));
  if(png.readUInt32BE(16)!==width||png.readUInt32BE(20)!==height)throw Error('Unexpected sprite dimensions: '+file);
  sprites[pose]={src:'data:image/png;base64,'+png.toString('base64'),width,height};
 }
 return '// Generated by build-sprites.cjs from the original PNGs.\nconst tutorialSpriteData='+JSON.stringify(sprites)+';\n';
}
if(require.main===module)fs.writeFileSync(path.join(__dirname,'sprite-data.js'),build());
module.exports={build};
