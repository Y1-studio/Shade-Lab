// Explicit local packages only: no directory scanning, network, or runtime file fetches.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

function inside(directory, relative) {
  if (typeof relative !== 'string' || !relative || relative.includes('\\') || path.isAbsolute(relative)) throw Error('Use relative forward-slash add-on paths.');
  const base = fs.realpathSync(directory), file = fs.realpathSync(path.resolve(base, relative));
  const rel = path.relative(base, file);
  if (!rel || rel === '..' || rel.startsWith('..' + path.sep) || path.isAbsolute(rel)) throw Error('Add-on path leaves its folder: ' + relative);
  return file;
}
function buildAddons(directory) {
  const registry = JSON.parse(fs.readFileSync(path.join(directory, 'registry.json'), 'utf8'));
  if (registry.version !== 1 || !Array.isArray(registry.addons)) throw Error('Expected add-on registry version 1.');
  const ids = new Set(), packages = [];
  for (const entry of registry.addons) {
    if (typeof entry.enabled !== 'boolean') throw Error('Each add-on needs an explicit enabled boolean.');
    const folder = inside(directory, entry.path);
    const meta = JSON.parse(fs.readFileSync(inside(folder, 'addon.json'), 'utf8'));
    if (typeof meta.id !== 'string' || !/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(meta.id) || ['constructor', 'prototype'].includes(meta.id) || ids.has(meta.id)) throw Error('Invalid or duplicate add-on ID: ' + meta.id);
    if (meta.apiVersion !== 1 || typeof meta.name !== 'string' || !meta.name.trim() || typeof meta.version !== 'string' || !meta.version.trim()) throw Error('Invalid metadata/API version for ' + meta.id);
    if (!Array.isArray(meta.scripts) || !meta.scripts.length || (meta.styles !== undefined && !Array.isArray(meta.styles))) throw Error('Add-on needs scripts and optional styles arrays: ' + meta.id);
    if (meta.requires!==undefined&&!Array.isArray(meta.requires)) throw Error('Dependencies must be an array: '+meta.id);
    if ((meta.requires || []).some(id => !ids.has(id))) throw Error('Register dependencies before ' + meta.id);
    ids.add(meta.id);
    const read = (file, extension) => {
      if (typeof file !== 'string' || path.extname(file) !== extension) throw Error('Expected ' + extension + ' file in ' + meta.id);
      return fs.readFileSync(inside(folder, file), 'utf8');
    };
    const js = meta.scripts.map(file => read(file, '.js')).join('\n;\n');
    const css = (meta.styles || []).map(file => read(file, '.css')).join('\n');
    // Styles must be self-contained for a truly offline, single-file distribution.
    if (/@import\b|url\s*\(/i.test(css)) throw Error('Add-on CSS cannot fetch files; embed visuals in its code: ' + meta.id);
    const info = { id: meta.id, name: meta.name, version: meta.version, apiVersion: meta.apiVersion, enabled: entry.enabled, requires: meta.requires || [] };
    const source = `(function () {\n'use strict';\ntry {\n${js}\n;\nShadeAddons.register(${JSON.stringify(info)}, addon, ${JSON.stringify(css)});\n} catch (error) { ShadeAddons.loadFailed(${JSON.stringify(info)}, error); }\n})();`;
    new vm.Script(source, { filename: entry.path + '/bundle.js' });
    packages.push(source);
  }
  return '// Generated by build-html.cjs. Edit individual add-on folders, not this file.\n' + packages.join('\n') + '\n';
}
module.exports = { buildAddons };
